# Streaming
# ============================================================

@app.post(
    "/explain/stream",
    summary = "Stream structured explanation from Gemini",
    description = "Streams explanation token-by-token in real time from the cloud model."
    )
@limiter.limit("3/minute")

async def stream_explanation(request: Request, data: ConceptRequest):
    
    async def event_generator():
        try:
            prompt = f"""You are a factual tutor.
            Provide a clear and structured explanation of the concept: {data.concept}.
            Explain it for a {data.level} learner.
            Keep it structured."""
            response = client.models.generate_content_stream(
                model = gemini_model,
                contents = prompt
            )

            for chunk in response:
                if chunk.text:
                    yield chunk.text
                    await asyncio.sleep(0.02)
        
        except Exception as e:
            yield f"[ERROR: Streaming Failed] {str(e)}"
            
    return StreamingResponse(event_generator(), media_type="text/plain")



@app.post(
    "/personalize/stream",
    summary = "Stream creative explanation from Local model",
    description = "Streams explanation token-by-token in real time from the local Ollama model."
    )
@limiter.limit("3/minute")

async def stream_personalized(request: Request, data: ConceptRequest):
    
    async def event_generator():
        try:
            url = "http://localhost:11434/api/generate"
            
            prompt = (
                    f"Rewrite this technical explanation in a highly engaging, fun, "
                    f"and personally relatable story or creative analogy for a {data.level} learner "
                    f"exploring Agentic AI. Be creative and do not exceed 4 sentences.\n\n"
                    f"Explain the concept of:\n\n---\n{data.concept}"
                )
            
            payload = {
                    "model": "phi3:mini",
                    "prompt": prompt,
                    "stream": True
                }
            
            with requests.post(url, json=payload, stream=True) as local_response:
                if local_response.status_code == 200:
                    for line in local_response.iter_lines():
                        if line:
                            decoded = line.decode("utf-8")
                            json_data = json.loads(decoded)

                            if "response" in json_data:
                                yield json_data["response"]

                            await asyncio.sleep(0.02)
                        
                else:
                    yield f"[ERROR: Local Model Failed] Status Code: {local_response.status_code}"
        
        except Exception as e:
            yield f"[ERROR: Streaming Failed] {str(e)}"
    
    return StreamingResponse(event_generator(), media_type="text/plain")
